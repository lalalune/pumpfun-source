import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createAdvancedCreatorFeeControl } from '../reconstruction/create-advanced-fee/client.mjs';
import { APP_ROOT, recover, verify } from '../scripts/original-create-advanced-fee.mjs';

function synthetic() {
  const slots = Array(39).fill(Symbol.for('react.memo_cache_sentinel'));
  let state, quote = { pair: { kind: 'pump' } }, language = 'first';
  const updates = [], translations = [];
  let translate = (key, vars) => { translations.push({ language, key, vars }); return `${language}:${key}`; };
  const jsx = (type, props) => ({ type, props });
  const control = createAdvancedCreatorFeeControl({
    createBoundStore(initialize) {
      state = initialize((patch) => { updates.push(patch); state = { ...state, ...patch }; });
      return (selector = (s) => s) => selector(state);
    },
    useQuoteState(selector) { return selector(quote); },
    useTranslation: () => ({ t: translate }),
    compiler(size) { assert.equal(size, 39); return slots; },
    jsxRuntime: { jsx, jsxs: jsx }, Collapsible: { Y: 'root', v: 'trigger', C: 'content' }, Input: 'input-port', Chevron: 'chevron-port',
  });
  return { ...control, updates, translations, state: () => state,
    setQuote(kind) { quote = { pair: { kind } }; },
    setLanguage(value) { language = value; translate = (key, vars) => { translations.push({ language, key, vars }); return `${language}:${key}`; }; } };
}
function nodes(tree) {
  if (!tree || typeof tree !== 'object') return [];
  return [tree, ...(Array.isArray(tree.props?.children) ? tree.props.children.flatMap(nodes) : nodes(tree.props?.children))];
}
const input = (tree) => nodes(tree).find((n) => n.type === 'input-port');
const error = (tree) => nodes(tree).find((n) => n.props?.id === 'create-coin-creator-fee-percent-error');

test('complete source closure enforces six roles, actual callers, 39slots and canonical generated bytes', async () => {
  assert.deepEqual(await verify(), { sources: 6, witnesses: 38, compilerSlots: 39, mounted: false });
  const { contract } = await recover();
  assert.ok(contract.witnesses.some((w) => w.label.includes('actual default Create advanced control mount')));
  assert.equal(contract.witnesses.filter((w) => w.label.includes('both fee projection consumers')).length, 2);
});

test('maintained source gate rejects changed control, schema and formatting through the actual verifier', async () => {
  const { client, contract } = await recover();
  for (const changed of [client + '\n', client.replace('Number(e) >= .01', 'Number(e) >= .02')]) {
    assert.notEqual(changed, client);
    await assert.rejects(verify(APP_ROOT, { client: Buffer.from(changed) }), /canonical source-derived bytes differ/);
  }
  for (const mutate of [(c) => c.witnesses.pop(), (c) => { c.behavior.visibility = 'all pairs'; }, (c) => { c.sources[0].sha256 = '0'.repeat(64); }]) {
    const changed = structuredClone(contract); mutate(changed);
    await assert.rejects(verify(APP_ROOT, { contract: Buffer.from(JSON.stringify(changed, null, 2) + '\n') }), /canonical source-derived bytes differ/);
  }
  await assert.rejects(verify(APP_ROOT, { contract: Buffer.from(JSON.stringify(contract)) }), /canonical source-derived bytes differ/);
});

test('full state initializes empty optional field and quote visibility keeps only stock/pump', () => {
  const host = synthetic();
  assert.equal(host.state().creatorFeePercent, '');
  assert.equal(host.store().creatorFeePercent, '');
  for (const kind of ['sol', 'usdc', 'unknown', 'PUMP']) { host.setQuote(kind); assert.equal(host.Control(), null); }
  for (const kind of ['stock', 'pump']) {
    host.setQuote(kind); const tree = host.Control();
    assert.equal(tree.type, 'root'); assert.equal(tree.props.defaultOpen, true);
    assert.equal(input(tree).props.value, ''); assert.equal(error(tree), undefined);
  }
});

test('actual controlled input and ARIA/error consumer keep all source attributes and optional label', () => {
  const host = synthetic(), tree = host.Control(), props = input(tree).props;
  assert.equal(props.id, 'create-coin-creator-fee-percent');
  assert.equal(props.type, 'text'); assert.equal(props.inputMode, 'decimal'); assert.equal(props.maxLength, 4); assert.equal(props.autoComplete, 'off');
  assert.equal(props['aria-invalid'], undefined); assert.equal(props['aria-describedby'], undefined);
  assert.ok(nodes(tree).some((n) => n.type === 'label' && n.props.htmlFor === props.id));
  assert.ok(nodes(tree).some((n) => n.type === 'span' && n.props.children === '(Optional)'));
});

test('full field change→state→validation→error/ARIA path preserves optional, decimal and range quirks', () => {
  const host = synthetic();
  for (const [value, invalid] of [['', false], ['0', true], ['.01', false], ['.1', false], ['1.', false], ['3', false], ['3.00', false], ['3.01', true], ['.', true], [' 1', true], ['1e0', true], ['-1', true], ['1.234', true]]) {
    const previous = host.Control(); input(previous).props.onChange({ target: { value } });
    assert.equal(host.state().creatorFeePercent, value, 'raw string preserved');
    assert.deepEqual(host.updates.at(-1), { creatorFeePercent: value });
    const tree = host.Control(), field = input(tree);
    assert.equal(field.props.value, value); assert.equal(field.props['aria-invalid'], invalid ? true : undefined);
    assert.equal(field.props['aria-describedby'], invalid ? 'create-coin-creator-fee-percent-error' : undefined);
    assert.equal(!!error(tree), invalid);
    if (invalid) assert.equal(error(tree).props.children, 'first:web.create.creator_fee_invalid');
  }
});

test('source callback has no length guard/trim while declared native maximum is four', () => {
  const host = synthetic();
  input(host.Control()).props.onChange({ target: { value: ' 1.234 ' } });
  assert.equal(host.state().creatorFeePercent, ' 1.234 ');
  assert.equal(input(host.Control()).props.maxLength, 4);
  assert.ok(error(host.Control()), 'synthetic event bypasses native maxlength; not a native user-entry claim');
});

test('39slot memo control preserves references and recomputes actual translator-dependent label/copy', () => {
  const host = synthetic(), first = host.Control(), second = host.Control();
  assert.equal(first, second); assert.equal(input(first).props.onChange, input(second).props.onChange);
  host.setLanguage('second'); const changed = host.Control();
  assert.notEqual(changed, second); assert.equal(input(changed).props.placeholder, 'second:web.create.creator_fee_placeholder');
  const call = host.translations.find((v) => v.language === 'second' && v.key === 'web.create.creator_fee_placeholder');
  assert.deepEqual(call.vars, { min_percent: .01, max_percent: 3 });
  assert.equal(input(changed).props.onChange, input(first).props.onChange, 'setter identity is the callback dependency');
});

