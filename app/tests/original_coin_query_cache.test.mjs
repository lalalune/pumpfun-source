function harness(extra = {}) {
  const client = queryClientPort(),
    calls = [];
  let now = 100000,
    query = {
      data: undefined,
      isLoading: false,
      error: null,
      isError: false,
      isLoadingError: false,
      refetch: () => Promise.resolve("refetched"),
    },
    options;
  const api = createCoinQuery({
    useMemoCache: memoPort(),
    useQuery: (o) => ((options = o), query),
    useQueryClient: () => client,
    clock: { now: () => now },
    getContractClient:
      () =>
      async (...args) => (calls.push(args), []),
    ...extra,
  });
  return {
    ...api,
    client,
    calls,
    get options() {
      return options;
    },
    set query(q) {
      query = { ...query, ...q };
    },
    set now(n) {
      now = n;
    },
  };
}
