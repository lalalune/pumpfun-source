test("actual verifier rejects source-derived code/contract mutations", async () => {
  const d = await derive(root);
  const changes = [
    { code: d.code.replace('credentials: "include"', 'credentials: "omit"') },
    { code: d.code.replace("const T = 6e4", "const T = 6e4 + 1") },
    { code: d.code.replace("...s,", "...{},") },
    { contract: { ...d.contract, callers: [] } },
    { contract: { ...d.contract, ports: [] } },
    { contract: { ...d.contract, witnesses: d.contract.witnesses.slice(1) } },
    { contract: { ...d.contract, productionOperationsQualified: 1 } },
  ];
  for (const changed of changes) {
    if (changed.code !== undefined)
      assert.notEqual(
        changed.code,
        d.code,
        "negative mutation must change generated bytes",
      );
    assert.notDeepEqual(changed, d);
    await assert.rejects(verify(root, changed));
  }
});
