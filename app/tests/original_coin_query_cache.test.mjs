test("actual loopbackPOST observes exact options/body, identity and third-arg HTTP rejection", async () => {
  const receipts = [];
  let mode = "ok",
    closed = false;
  const server = createServer(async (req, res) => {
    let body = "";
    for await (const c of req) body += c;
    receipts.push({
      method: req.method,
      url: req.url,
      headers: req.headers,
      body: JSON.parse(body),
    });
    res.writeHead(mode === "ok" ? 200 : 503, {
      "Content-Type": "application/json",
    });
    res.end(
      JSON.stringify(mode === "ok" ? [coin("b")] : { error: "synthetic" }),
    );
  });
  server.listen(0, "127.0.0.1");
  await once(server, "listening");
  try {
    const url = `http://127.0.0.1:${server.address().port}/batch`;
    let options;
    const h = harness({
      getContractClient: () => async (op, o) => {
        assert.equal(op, "POST /coins-v2/mints");
        options = o;
        const response = await fetch(url, {
          method: "POST",
          body: JSON.stringify(o.body),
          credentials: o.credentials,
          headers: { "Content-Type": "application/json" },
        });
        for (const fn of o.hooks.afterResponse)
          await fn({ synthetic: "request" }, o, response);
        return response.json();
      },
    });
    assert.deepEqual(
      await h.readCoins(["b", "a", "b"], { includeNsfw: true }),
      [coin("b")],
    );
    assert.equal(options.credentials, "include");
    assert.deepEqual(Object.keys(options).sort(), [
      "body",
      "credentials",
      "hooks",
    ]);
    mode = "error";
    await assert.rejects(
      h.readCoins(["bad"]),
      /Failed to fetch coins: Service Unavailable/,
    );
    assert.equal(receipts.length, 2);
    assert.deepEqual(receipts[0].body, { mints: ["b", "a", "b"] });
    assert.equal(receipts[0].method, "POST");
    for (const r of receipts) {
      assert.equal(r.url, "/batch");
      assert.equal(r.headers.cookie, undefined);
      assert.equal(r.headers.authorization, undefined);
    }
  } finally {
    server.closeAllConnections();
    await new Promise((resolve) =>
      server.close(() => {
        closed = true;
        resolve();
      }),
    );
  }
  assert.equal(closed, true);
});
