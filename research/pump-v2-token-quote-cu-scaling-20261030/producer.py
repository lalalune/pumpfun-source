#!/usr/bin/env python3
"""Pump Main token-quote v2 trades: compute-unit scaling, original vs rebuild.

buy_v2 / sell_v2 on a token-quote curve (Token-2022 quote mint with a
TransferFeeConfig, and an SPL Token quote mint). One operand per series is
swept: the token amount (10^0..10^14), the stub fee bps (protocol / creator
branch on or off) and the Token-2022 transfer-fee bps. The per-series
compute-unit range on each image and the per-case original-minus-rebuild
difference are reported in `series`.

pump_fees is not one of the two images. Its slot holds a deterministic
9-instruction SBPFv0 program generated by this file (`fee_stub`) that returns
the case's fee_bps as the 24-byte `Fees` value. Both images see the same stub.

Pump runs under the upgradeable loader (program account + programdata), the
mainnet layout; LiteSVM's builtin SPL Token / Token-2022 / ATA programs. All
account state is synthetic (IDL layouts), keys come from fixed seeds, the clock
is fixed, one fresh VM per case, no network. The full initial account set of
every case is written to runtime/plan.json.gz, so verify.py replays without the
repository.

Usage:
  python3 producer.py --root <repo> --images '{"original": "...", "candidate": "..."}' --out <packet dir>
"""
