def tf(bps, maximum=2**64 - 1, newer_bps=None, newer_epoch=0):
    newer_bps = bps if newer_bps is None else newer_bps
    return mint22([tfc_entry(fee(0, maximum, bps), fee(newer_epoch, maximum, newer_bps))])


def state(quote='t22', mint_data=None, curve_kw=None, missing=(), balances=None, user_tokens=10**12, glob_kw=None,
          recipient=FEE_RECIPIENT, buyback=BUYBACK[0]):
    """quote: 't22' (Token-2022 quote mint QUOTE22, 100 bps by default) or 'spl' (SPL Token quote mint)."""
    q, prog = (QUOTE22, TOKEN22) if quote == 't22' else (QUOTE_SPL, TOKEN)
    fc_bump = Pubkey.find_program_address([b'fee_config', bytes(PROGRAM)], FEE_PROGRAM)[1]
    if mint_data is None:
        mint_data = tf(100) if quote == 't22' else mint_base()
    curve_kw = dict(curve_kw or {})
    bal = {'curve': curve_kw.get('rqr', 0), 'user': USER_QUOTE, 'vault': 0, 'uva': 0, 'fee_recipient': 0, 'buyback': 0}
    bal.update(balances or {})
    st = {
        GLOBAL: (10**9, PROGRAM, global_data(**(glob_kw or {}))),
        MINT: (10**9, TOKEN, mint_base()),
        q: (10**9, prog, mint_data),
        CURVE: (RENT_166, PROGRAM, curve_data(q, **curve_kw)),
        ata(CURVE, MINT): (10**9, TOKEN, token_data(MINT, CURVE, curve_kw.get('rtr', V['rtr']))),
        ata(USER.pubkey(), MINT): (10**9, TOKEN, token_data(MINT, USER.pubkey(), user_tokens)),
        GVA: (10**9, PROGRAM, gva_data()),
        FEE_CONFIG: (10**9, FEE_PROGRAM, fee_config_data(fc_bump)),
        USER.pubkey(): (10**13, SYSTEM, b''),
        recipient: (10**9, SYSTEM, b''),
        buyback: (10**9, SYSTEM, b''),
    }
    holders = dict(QUOTE_HOLDERS, fee_recipient=recipient, buyback=buyback)
    for name, holder in holders.items():
        if name not in missing:
            st[ata(holder, q, prog)] = (10**9, prog, token_data(q, holder, bal[name], prog == TOKEN22))
    return st


def v2_metas(kind, quote='t22', recipient=FEE_RECIPIENT, buyback=BUYBACK[0]):
    """IDL account order for buy_v2 / buy_exact_quote_in_v2 (27) and sell_v2 (26)."""
    q, qp = (QUOTE22, TOKEN22) if quote == 't22' else (QUOTE_SPL, TOKEN)
    holders = dict(QUOTE_HOLDERS, fee_recipient=recipient, buyback=buyback)
    qa = lambda holder: ata(holders[holder], q, qp)
    w = lambda k: AccountMeta(k, False, True)
    r = lambda k: AccountMeta(k, False, False)
    metas = [r(GLOBAL), r(MINT), r(q), r(TOKEN), r(qp), r(ATA_PROGRAM),
             w(recipient), w(qa('fee_recipient')), w(buyback), w(qa('buyback')),
             w(CURVE), w(ata(CURVE, MINT)), w(qa('curve')), AccountMeta(USER.pubkey(), True, True),
             w(ata(USER.pubkey(), MINT)), w(qa('user')), w(VAULT), w(qa('vault')), r(SHARING)]
    if kind != 'sell_v2':
        metas.append(r(GVA))
    metas += [w(UVA), w(qa('uva')), r(FEE_CONFIG), r(FEE_PROGRAM), r(SYSTEM), r(EVENT_AUTHORITY), r(PROGRAM)]
    return metas


def then(kind, a, b, quote='t22'):
    return {'instruction': kind, 'data_hex': (IX[kind] + struct.pack('<QQ', a, b)).hex(),
            'metas': [[str(m.pubkey), m.is_signer, m.is_writable] for m in v2_metas(kind, quote)]}


def case(name, kind, a, b, st=None, quote='t22', epoch=0, fees=DEFAULT_FEES, note='', seq=None,
         recipient=FEE_RECIPIENT, buyback=BUYBACK[0]):
    st = st if st is not None else state(quote, recipient=recipient, buyback=buyback)
    out = {'case': f'{kind}/{name}', 'instruction': kind, 'note': note, 'epoch': epoch, 'fee_bps': list(fees),
           'data_hex': (IX[kind] + struct.pack('<QQ', a, b)).hex(),
           'metas': [[str(m.pubkey), m.is_signer, m.is_writable] for m in v2_metas(kind, quote, recipient, buyback)],
           'accounts': [[str(k), lam, str(owner), data.hex()] for k, (lam, owner, data) in
                        sorted(st.items(), key=lambda kv: str(kv[0]))]}
    if seq:
        out['then'] = seq
    return out


# Token-2022 transfer-fee arithmetic and pump curve formulas, used only to place boundaries.
def tf_fee(bps, maximum, amount):
    if bps == 0 or amount == 0:
        return 0
    return min(-(-amount * bps // 10000), maximum)


def tf_pre(bps, maximum, amount):
    if bps == 0 or amount == 0:
        return amount
    if bps == 10000:
        return amount + maximum
    raw = -(-amount * 10000 // (10000 - bps))
    return amount + maximum if raw - amount >= maximum else raw


def ceil_bps(x, bps):
    return -(-x * bps // 10000)


def buy_limit(amount, bps=100, maximum=2**64 - 1, fees=DEFAULT_FEES, vqr=V['vqr'], vtr=V['vtr']):
    quote = amount * vqr // (vtr - amount) + 1
    return tf_pre(bps, maximum, quote) + ceil_bps(quote, fees[1]) + ceil_bps(quote, fees[2])


def sell_net(amount, bps=100, maximum=2**64 - 1, fees=DEFAULT_FEES, vqr=V['vqr'], vtr=V['vtr']):
    quote = amount * vqr // (vtr + amount)
    output = quote - ceil_bps(quote, fees[1]) - ceil_bps(quote, fees[2])
    return output - tf_fee(bps, maximum, output)


def plan():
    big = 2**64 - 1
    sk = {'rqr': 10**12}
    rich = lambda quote='t22', **kw: state(quote, curve_kw=dict(sk), balances={'curve': 10**12}, user_tokens=10**15, **kw)
    out = []
    # 1. amount sweeps, Token-2022 quote (100 bps transfer fee)
    for e in (0, 2, 4, 6, 8, 10, 12, 14):
        out.append(case(f'amount-t22/1e{e}', 'buy_v2', 10**e, big))
    for e in (0, 2, 4, 6, 8, 10, 12, 14):
        out.append(case(f'amount-t22/1e{e}', 'sell_v2', 10**e, 0, rich()))
    # 2. amount sweeps, SPL Token quote
    for e in (0, 6, 10, 14):
        out.append(case(f'amount-spl/1e{e}', 'buy_v2', 10**e, big, state('spl'), quote='spl'))
    for e in (0, 6, 10, 14):
        out.append(case(f'amount-spl/1e{e}', 'sell_v2', 10**e, 0, rich('spl'), quote='spl'))
    # 3. fee branches (does the native-SOL creator-branch CU offset also appear on token quotes?)
    for name, fees in (('0-0-0', (0, 0, 0)), ('0-95-0', (0, 95, 0)), ('0-0-30', (0, 0, 30))):
        out.append(case(f'fee-t22/{name}', 'buy_v2', 10**9, big, fees=fees))
        out.append(case(f'fee-t22/{name}', 'sell_v2', 10**9, 0, rich(), fees=fees))
        out.append(case(f'fee-spl/{name}', 'buy_v2', 10**9, big, state('spl'), quote='spl', fees=fees))
    # 4. Token-2022 transfer-fee bps on a 10^9-token buy
    for bps in (0, 1, 100, 9999):
        out.append(case(f'tf-bps/{bps}', 'buy_v2', 10**9, big, state(mint_data=tf(bps))))
    return out


