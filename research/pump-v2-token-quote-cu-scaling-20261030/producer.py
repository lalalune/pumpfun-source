def token_amount(accounts, key):
    a = accounts.get(str(key))
    if a is None or len(a[2]) < 144:
        return None
    return struct.unpack_from('<Q', bytes.fromhex(a[2]), 64)[0]


def quote_deltas(c, receipt):
    """Quote-token balance change of each holder's quote ATA (withheld transfer fees are not balance)."""
    before = {k: (lam, owner, data) for k, lam, owner, data in c['accounts']}
    q = c['metas'][2][0]
    qp = Pubkey.from_string(c['metas'][4][0])
    out = {}
    for label, holder in LABELS.items():
        key = ata(holder, Pubkey.from_string(q), qp)
        b = before.get(str(key))
        b_amt = struct.unpack_from('<Q', bytes.fromhex(b[2]), 64)[0] if b else 0
        a_amt = token_amount(receipt['accounts_after'], key)
        if a_amt is not None and a_amt != b_amt:
            out[label] = a_amt - b_amt
    base_before = struct.unpack_from('<Q', bytes.fromhex(before[str(ata(USER.pubkey(), MINT))][2]), 64)[0]
    base_after = token_amount(receipt['accounts_after'], ata(USER.pubkey(), MINT))
    if base_after is not None and base_after != base_before:
        out['user_base_tokens'] = base_after - base_before
    return dict(sorted(out.items()))


TRADE_EVENT = bytes.fromhex('bddb7fd34ee661ee')


def trade_event(e):
    """Decode the TradeEvent layout of programs/pump/src/lib.rs (Shareholder = Pubkey + u16)."""
    d = base64.b64decode(e)
    if d[:8] != TRADE_EVENT:
        return None
    o = 8
    def take(fmt):
        nonlocal o
        v = struct.unpack_from(fmt, d, o)
        o += struct.calcsize(fmt)
        return v
    ev = {}
    o += 32
    ev['sol_amount'], ev['token_amount'], ev['is_buy'] = take('<QQB')
    o += 32 + 8  # user, timestamp
    ev['virtual_sol_reserves'], ev['virtual_token_reserves'], ev['real_sol_reserves'], ev['real_token_reserves'] = take('<QQQQ')
    ev['fee_recipient'] = str(Pubkey(d[o:o + 32]))
    o += 32
    ev['fee_basis_points'], ev['fee'] = take('<QQ')
    o += 32
    ev['creator_fee_basis_points'], ev['creator_fee'] = take('<QQ')
    o += 1 + 8 * 4
    (n,) = take('<I')
    ev['ix_name'] = d[o:o + n].decode()
    o += n
    ev['mayhem_mode'], ev['cashback_fee_basis_points'], ev['cashback'], ev['buyback_fee_basis_points'], \
        ev['buyback_fee'] = take('<BQQQQ')
    (n,) = take('<I')
    ev['shareholders'] = n
    o += n * 34
    o += 32
    ev['quote_amount'], ev['virtual_quote_reserves'], ev['real_quote_reserves'], ev['holder_rewards_bps'], \
        ev['holder_rewards'], ev['creator_fee_unclaimed'], ev['unparsed_trailing_field'] = take('<QQQQQQQ')
    ev['trailing_bytes'] = len(d) - o
    ev['is_buy'] = bool(ev['is_buy'])
    ev['mayhem_mode'] = bool(ev['mayhem_mode'])
    return ev


def curve_after(receipt):
    a = receipt['accounts_after'].get(str(CURVE))
    if a is None:
        return None
    d = bytes.fromhex(a[2])
    vtr, vqr, rtr, rqr, tts = struct.unpack_from('<QQQQQ', d, 8)
    return {'virtual_token_reserves': vtr, 'virtual_quote_reserves': vqr, 'real_token_reserves': rtr,
            'real_quote_reserves': rqr, 'complete': d[48]}


def summarize(cases, original, candidate):
    rows = []
    for c, ro, rc in zip(cases, original, candidate):
        rows.append({'case': c['case'], 'instruction': c['instruction'], 'note': c['note'],
                     'args': list(struct.unpack_from('<QQ', bytes.fromhex(c['data_hex']), 8)),
                     'fee_bps_returned_by_stub': c['fee_bps'], 'then': [t['instruction'] for t in c.get('then', [])],
                     'error_original': ro['error'], 'error_candidate': rc['error'],
                     'custom_code': custom_code(ro['error']),
                     'error_name': {'original': anchor_name(ro['logs']), 'candidate': anchor_name(rc['logs'])},
                     'reached_fee_cpi': {'original': ro['reached_fee_cpi'], 'candidate': rc['reached_fee_cpi']},
                     'compute_units': {'original': ro['compute_units'], 'candidate': rc['compute_units'],
                                       'original_minus_candidate': ro['compute_units'] - rc['compute_units']},
                     'logs_equal': ro['logs'] == rc['logs'],
                     'differing_log_lines': classify_logs(ro['logs'], rc['logs']),
                     'behavior_differences': [k for k in BEHAVIOR if ro[k] != rc[k]],
                     'quote_deltas': quote_deltas(c, ro), 'curve_after': curve_after(ro),
                     'trade_events': [t for t in map(trade_event, ro['events']) if t is not None]})
    stops, deltas, kinds = {}, {}, {}
    for r in rows:
        stop = 'success' if r['error_original'] is None else (r['error_name']['original'] or str(r['custom_code']))
        stops[stop] = stops.get(stop, 0) + 1
        dk = f"{r['compute_units']['original_minus_candidate']}:{stop}"
        deltas[dk] = deltas.get(dk, 0) + 1
        kind = ','.join(sorted({d['kind'] for d in r['differing_log_lines']})) or 'none'
        kinds[kind] = kinds.get(kind, 0) + 1
    return {'case_count': len(rows),
            'behavior_mismatches': [r['case'] for r in rows if r['behavior_differences']],
            'reached_fee_cpi_cases': sum(r['reached_fee_cpi']['original'] for r in rows),
            'compute_units_equal_cases': sum(r['compute_units']['original_minus_candidate'] == 0 for r in rows),
            'logs_equal_cases': sum(r['logs_equal'] for r in rows),
            'cases_by_stop': dict(sorted(stops.items())),
            'compute_unit_delta_by_stop': dict(sorted(deltas.items())),
            'log_difference_kinds': dict(sorted(kinds.items())),
            'series': series(rows), 'cases': rows}


def series(rows):
    """Group cases by the first two name parts; CU range per image and the set of differences."""
    out = {}
    for r in rows:
        key = '/'.join(r['case'].split('/')[:2])
        s = out.setdefault(key, {'cases': 0, 'successes': 0, 'original_min': None, 'original_max': None,
                                 'candidate_min': None, 'candidate_max': None, 'differences': {}})
        cu = r['compute_units']
        s['cases'] += 1
        s['successes'] += r['error_original'] is None
        for img in ('original', 'candidate'):
            lo, hi = s[img + '_min'], s[img + '_max']
            s[img + '_min'] = cu[img] if lo is None else min(lo, cu[img])
            s[img + '_max'] = cu[img] if hi is None else max(hi, cu[img])
        d = str(cu['original_minus_candidate'])
        s['differences'][d] = s['differences'].get(d, 0) + 1
    for s in out.values():
        s['original_spread'] = s['original_max'] - s['original_min']
        s['candidate_spread'] = s['candidate_max'] - s['candidate_min']
    return out


def write_gz(path, text):
    path.write_bytes(gzip.compress(text.encode(), mtime=0))


