//! fails, and the text of the line Anchor logs for it.
//!
//! Checked against `evidence/original/pump/deployed.so` on LiteSVM by
//! `tests/test_error_sites_trades_captured.py`, which records the failing
//! transactions of the fixed cases of those captured tests. Each row was read
//! from a log of the captured program. This is not a byte-identity claim.
//!
//! Unconfirmed: sites and accounts those fixed cases do not reach, and the
//! `Left:` / `Right:` lines logged after some constraints.

/// How the line names the place that failed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
