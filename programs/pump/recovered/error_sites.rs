fn error(code: u64) -> Option<(&'static str, &'static str)> {
    ERRORS.iter().find(|e| e.0 == code).map(|e| (e.1, e.2))
}

/// The line the handler logs at this place, or `None` if no row names it.
pub fn line(handler: &str, kind: Kind, place: &str, code: u64) -> Option<String> {
    if !SITES.iter().any(|s| s.0 == handler && s.1 == kind && s.2 == place && s.3 == code) {
        return None;
    }
    let (name, message) = error(code)?;
    let tail = format!("Error Code: {name}. Error Number: {code}. Error Message: {message}.");
    Some(match kind {
        Kind::Thrown => format!("AnchorError thrown in programs/pump/src/{place}. {tail}"),
        Kind::Account => format!("AnchorError caused by account: {place}. {tail}"),
        Kind::Program => format!("ProgramError caused by account: {place}. {tail}"),
        Kind::Occurred => format!("AnchorError occurred. {tail}"),
    })
}

/// Every `file:line` from which the handler throws this code, sorted.
pub fn thrown_sites(handler: &str, code: u64) -> Vec<&'static str> {
    let mut places: Vec<&'static str> = SITES
        .iter()
        .filter(|s| s.0 == handler && s.1 == Kind::Thrown && s.3 == code)
        .map(|s| s.2)
        .collect();
    places.sort_unstable();
    places
}

/// Name and message of a code in the table.
pub fn name_and_message(code: u64) -> Option<(&'static str, &'static str)> {
    error(code)
}
