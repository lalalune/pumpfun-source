//! Captured Pump error log lines: which source site or account each handler
//! names when it fails, and the text of the line Anchor logs for it.
//!
//! Checked against `evidence/original/pump/deployed.so` on LiteSVM by
//! `tests/test_error_sites_captured.py`, which drives failing cases of the other
//! captured tests. Each row was read from a log of the captured program; the
//! names and messages of the 6000 range also match `evidence/upstream/pump.json`.
//! Not linked into the SBF crate. This is not a byte-identity claim.
//!
//! Unconfirmed (미확인, outside the checked inputs): sites and accounts no test
//! case reaches, and the `Left:` / `Right:` lines logged after some constraints.

/// How the line names the place that failed.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    /// `AnchorError thrown in programs/pump/src/<file>:<line>.`
    Thrown,
    /// `AnchorError caused by account: <name>.`
    Account,
    /// `ProgramError caused by account: <name>.`
    Program,
    /// `AnchorError occurred.`
    Occurred,
}

