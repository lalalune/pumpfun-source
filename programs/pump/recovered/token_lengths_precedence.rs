//! Captured precedence of a handler read of a token account over the
//! errors of the instruction that opens it.
//!
//! `token_lengths.rs` names how each slot is read, but left one thing
//! unconfirmed: whether a handler read comes before every handler error.
//! Its replay only kept twins that succeed or fail with a Pump custom
//! error of 6000 or more. This model answers the question against the
//! whole error set the captured fixtures produce -- Anchor errors
//! (2xxx), errors surfaced from token CPIs (3012, 4102), token-program
//! errors, the Pump Fees program, a panic, and runtime failures (rent,
//! system) -- for every slot `read_of` calls `Handler`.
//!
//! `precedence` takes the instruction, the slot and the twin outcome
//! (the outcome at the standard length, as the test harness names it:
//! `ok`, `panic`, `fees`, `rent`, or `<program>:<error>`) and says
//! whether reshaping the slot to a length the Pump decoder refuses
//! leaves the twin outcome standing or replaces it with the decoder's
//! `InvalidAccountData`. The answer does not depend on which refused
//! length is stored. One error is case-split and stays unconfirmed:
//! 6041 on `buy_exact_quote_in_v2` stands in one replayed case and is
//! preempted in another.
//!
//! Two shapes stand out. On `migrate_v2` the pool token account is
//! opened behind every replayed error: only a passing twin is stopped
//! by the read. On the v2 and v3 trade routes the quote bonding curve
//! and quote user accounts are opened before the check that raises
//! 6004, and the remaining quote accounts after it, so 6004 is
//! preempted for the first pair and stands for the rest.
//!
//! The tables name every (instruction, slot, twin) the replay
//! produced; any other twin is unconfirmed.
//!
//! Checked against `evidence/original/pump/deployed.so` and the
//! captured token programs by
//! `tests/test_token_lengths_precedence_captured.py`. Not linked into
//! the SBF crate. This is not a byte-identity claim.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Precedence {
    /// The twin outcome is unchanged: the error is raised first.
    Stands,
    /// The read fails first: the outcome becomes `InvalidAccountData`.
    Preempts,
    /// Both outcomes were seen, or the twin was never replayed.
    Unconfirmed,
}

