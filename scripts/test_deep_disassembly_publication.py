#!/usr/bin/env python3
"""Deep disassembly packets are published only into clean output directories."""
import contextlib
import hashlib
import io
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

SCRIPTS = Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPTS))
import deep_disassembly  # noqa: E402


def generate(output):
    argv = ["deep_disassembly.py", "--program", "mayhem", "--output", str(output)]
    with mock.patch.object(sys, "argv", argv), contextlib.redirect_stdout(io.StringIO()):
        return deep_disassembly.main()


def generate_program(program, output):
    argv = ["deep_disassembly.py", "--program", program, "--output", str(output)]
    with mock.patch.object(sys, "argv", argv), contextlib.redirect_stdout(io.StringIO()):
        return deep_disassembly.main()


def packet_hashes(output):
    return {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in output.iterdir()
    }


class DeepDisassemblyPublicationTests(unittest.TestCase):
    def test_stale_entry_is_rejected_before_any_packet_file_is_written(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            output.mkdir()
            (output / "stale.txt").write_text("not generated by this analysis\n")
            with self.assertRaisesRegex(ValueError, "unexpected packet entry: stale.txt"):
                generate(output)
            self.assertEqual([path.name for path in output.iterdir()], ["stale.txt"])

    def test_regenerated_packet_still_verifies(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            self.assertEqual(generate(output), 0)
            self.assertEqual(generate(output), 0)
            completed = subprocess.run([sys.executable, "-I", "-B", str(output / "verify.py")],
                                       capture_output=True, text=True)
            self.assertEqual(completed.returncode, 0, completed.stdout + completed.stderr)

    def test_failed_replacement_preserves_the_prior_complete_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            self.assertEqual(generate(output), 0)
            before = packet_hashes(output)
            real_write_text = Path.write_text

            def fail_syscall_report(path, *args, **kwargs):
                if path.name == "syscall-usage.json":
                    raise OSError("injected packet write failure")
                return real_write_text(path, *args, **kwargs)

            with mock.patch.object(Path, "write_text", fail_syscall_report):
                with self.assertRaisesRegex(OSError, "injected packet write failure"):
                    generate_program("pump_fees", output)

            after = packet_hashes(output)
            self.assertEqual(sorted(after), sorted(before))
            changed = sorted(name for name in before if after[name] != before[name])
            self.assertFalse(
                changed, f"failed analysis partially replaced the prior packet: {changed}"
            )
            self.assertEqual(
                sorted(path.name for path in output.parent.iterdir()),
                ["packet"],
                "failed analysis left a staging directory behind",
            )

    def test_failure_does_not_publish_a_new_partial_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            real_write_text = Path.write_text

            def fail_syscall_report(path, *args, **kwargs):
                if path.name == "syscall-usage.json":
                    raise OSError("injected packet write failure")
                return real_write_text(path, *args, **kwargs)

            with mock.patch.object(Path, "write_text", fail_syscall_report):
                with self.assertRaisesRegex(OSError, "injected packet write failure"):
                    generate(output)

            self.assertFalse(output.exists(), "failed analysis published a partial packet")
            self.assertEqual(list(output.parent.iterdir()), [])

    def test_replacement_retains_prior_packet_and_late_additions(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output, staging = root / 'packet', root / 'staging'
            output.mkdir(); staging.mkdir()
            (output / 'old').write_bytes(b'old evidence')
            output.chmod(0o700)
            identity = deep_disassembly.directory_identity(output)
            (output / 'late').write_bytes(b'concurrent addition')
            (staging / 'new').write_bytes(b'new evidence')
            deep_disassembly.publish_packet(staging, output, identity)
            self.assertEqual((output / 'new').read_bytes(), b'new evidence')
            self.assertEqual(output.stat().st_mode & 0o777, 0o700)
            backups = list(root.glob('.packet.previous-*'))
            self.assertEqual(len(backups), 1)
            self.assertEqual((backups[0] / 'old').read_bytes(), b'old evidence')
            self.assertEqual((backups[0] / 'late').read_bytes(), b'concurrent addition')

    def test_native_publish_failure_preserves_late_empty_destination(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output, staging = root / 'packet', root / 'staging'
            staging.mkdir()
            (staging / 'new').write_bytes(b'new evidence')
            rename = deep_disassembly.rename_directory
            def competing_writer(source, destination, **kwargs):
                output.mkdir()
                return rename(source, destination, **kwargs)
            with mock.patch.object(deep_disassembly, 'rename_directory', competing_writer):
                with self.assertRaises(FileExistsError):
                    deep_disassembly.publish_packet(staging, output, None)
            self.assertTrue(output.is_dir())
            self.assertEqual(list(output.iterdir()), [])
            self.assertFalse(staging.exists())

    def test_exchange_failure_keeps_existing_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output, staging = root / 'packet', root / 'staging'
            output.mkdir(); staging.mkdir()
            (output / 'old').write_bytes(b'old evidence')
            identity = deep_disassembly.directory_identity(output)
            with mock.patch.object(deep_disassembly, 'rename_directory', side_effect=OSError('exchange refused')):
                with self.assertRaisesRegex(OSError, 'exchange refused'):
                    deep_disassembly.publish_packet(staging, output, identity)
            self.assertEqual((output / 'old').read_bytes(), b'old evidence')
            self.assertFalse(staging.exists())

    def test_directory_replaced_during_exchange_is_restored_without_deletion(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output, staging = root / 'packet', root / 'staging'
            output.mkdir(); staging.mkdir()
            (output / 'old').write_bytes(b'old evidence')
            (staging / 'new').write_bytes(b'new evidence')
            identity = deep_disassembly.directory_identity(output)
            rename = deep_disassembly.rename_directory
            calls = 0
            def competing_writer(source, destination, **kwargs):
                nonlocal calls
                calls += 1
                if calls == 1:
                    output.rename(root / 'writer-moved-old')
                    output.mkdir()
                    (output / 'other').write_bytes(b'other writer')
                return rename(source, destination, **kwargs)
            with mock.patch.object(deep_disassembly, 'rename_directory', competing_writer):
                with self.assertRaisesRegex(ValueError, 'changed during publication'):
                    deep_disassembly.publish_packet(staging, output, identity)
            self.assertEqual((output / 'other').read_bytes(), b'other writer')
            self.assertEqual((staging / 'new').read_bytes(), b'new evidence')
            self.assertEqual((root / 'writer-moved-old' / 'old').read_bytes(), b'old evidence')


if __name__ == "__main__":
    unittest.main()
