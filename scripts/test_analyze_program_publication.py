from analyze_program import analyze_program


def packet_hashes(output):
    return {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in output.iterdir()
    }


class AnalyzeProgramPublicationTests(unittest.TestCase):
    def test_report_counts_eight_byte_slots_in_a_real_lddw_capture(self):
        # LDDW is one logical instruction occupying two eight-byte slots.
        elf = analyzer.Elf(analyzer.REPO / 'evidence/original/pump_fees/deployed.so')
        text = elf.b[elf.file_offset(elf.lo, elf.hi - elf.lo):
                     elf.file_offset(elf.lo, elf.hi - elf.lo) + elf.hi - elf.lo]
        offset = logical = lddw = 0
        while offset < len(text):
            wide = text[offset] == 0x18
            offset += 16 if wide else 8
            logical += 1
            lddw += wide
        self.assertEqual(offset, len(text))
        slots = len(text) // 8
        self.assertGreater(lddw, 0)
        self.assertEqual(slots, logical + lddw)
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / 'packet'
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program('pump_fees', output), 0)
            summary = json.loads((output / 'summary.json').read_text())
            self.assertEqual(summary['text_section']['size'], len(text))
            readme = (output / 'README.md').read_text()
            self.assertIn(f'{len(text):,} bytes ({slots:,} 8-byte instruction slots)', readme)
            self.assertNotIn('BPF instructions', readme)
            self.assertIn('| Address | Size (bytes) | 8-byte Slots | Name |', readme)
            rows = re.findall(r'^\| (0x[0-9a-f]+) \| ([0-9,]+) \| ([0-9,]+) \|',
                              readme, re.MULTILINE)
            self.assertEqual(len(rows), 20)
            for _, size, count in rows:
                self.assertEqual(int(size.replace(',', '')) // 8, int(count.replace(',', '')))

    def test_program_help_lists_every_analyzable_program(self):
        # --program accepts any evidence/original/<name> that has deployed.so
        # (analyze_program reads that path directly), so its help must name the
        # same set. pump_fees is analyzed successfully elsewhere in this suite
        # yet was missing from the enumerated help.
        supported = {
            path.parent.name
            for path in (analyzer.REPO / 'evidence/original').glob('*/deployed.so')
        }
        self.assertIn('pump_fees', supported)
        result = subprocess.run(
            [sys.executable, str(analyzer.REPO / 'scripts/analyze_program.py'), '--help'],
            capture_output=True, text=True,
            env={**os.environ, 'COLUMNS': '200'},
        )
        self.assertEqual(result.returncode, 0)
        match = re.search(r'Program name: ([^\n]*)', result.stdout)
        self.assertIsNotNone(match, result.stdout)
        listed = {token.strip() for token in match.group(1).split(',') if token.strip()}
        self.assertEqual(listed, supported)

    def test_unexpected_existing_entry_is_rejected_before_publication(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            output.mkdir()
            stale = output / "stale.txt"
            stale.write_text("not generated by this analysis\n")

            with contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, "unexpected packet entry"):
                    analyze_program("mayhem", output)

            self.assertEqual([path.name for path in output.iterdir()], ["stale.txt"])

    def test_symlinked_packet_entry_is_rejected_before_publication(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / "packet"
            output.mkdir()
            outside = root / "outside.json"
            outside.write_text("sentinel\n", encoding="utf-8")
            try:
                os.symlink(outside, output / "summary.json")
            except (OSError, NotImplementedError, AttributeError) as error:
                self.skipTest(f"creating links is not permitted: {error}")

            with contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, "packet entry is not a regular file"):
                    analyze_program("mayhem", output)

            self.assertEqual(outside.read_text(encoding="utf-8"), "sentinel\n")
            self.assertTrue((output / "summary.json").is_symlink())

    def test_symlinked_output_directory_is_rejected(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            outside = root / "outside"
            outside.mkdir()
            output = root / "packet"
            try:
                os.symlink(outside, output, target_is_directory=True)
            except (OSError, NotImplementedError, AttributeError) as error:
                self.skipTest(f"creating links is not permitted: {error}")

            with contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, "output directory is a link"):
                    analyze_program("mayhem", output)

            self.assertEqual(list(outside.iterdir()), [])


    def test_packet_bytes_do_not_follow_the_host_line_ending(self):
        # Model Windows text-I/O defaults at the actual file-open boundary.
        # Patching os.linesep alone does not change CPython TextIOWrapper.
        real_open = Path.open

        def windows_text_open(path, mode="r", buffering=-1, encoding=None,
                              errors=None, newline=None):
            if "b" not in mode and any(flag in mode for flag in "wax"):
                if newline is None:
                    newline = "\r\n"
                if encoding is None:
                    encoding = "cp1252"
            return real_open(path, mode, buffering=buffering, encoding=encoding,
                             errors=errors, newline=newline)

        with tempfile.TemporaryDirectory() as temporary:
            control = Path(temporary) / "control"
            output = Path(temporary) / "windows-defaults"
            with contextlib.redirect_stdout(io.StringIO()):
                analyze_program("mayhem", control)
                with mock.patch.object(Path, "open", windows_text_open):
                    analyze_program("mayhem", output)
            self.assertEqual(sorted(p.name for p in control.iterdir()),
                             sorted(p.name for p in output.iterdir()))
            for path in sorted(output.iterdir()):
                with self.subTest(entry=path.name):
                    self.assertEqual(path.read_bytes(),
                                     (control / path.name).read_bytes())
                    self.assertNotIn(b"\r", path.read_bytes())

    def test_failed_replacement_preserves_the_prior_complete_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program("mayhem", output), 0)
            before = packet_hashes(output)
            real_write_text = Path.write_text

            def fail_call_graph(path, *args, **kwargs):
                if path.name == "call-graph.json":
                    raise OSError("injected packet write failure")
                return real_write_text(path, *args, **kwargs)

            with mock.patch.object(Path, "write_text", fail_call_graph):
                with self.assertRaisesRegex(OSError, "injected packet write failure"):
                    with contextlib.redirect_stdout(io.StringIO()):
                        analyze_program("pump", output)

            after = packet_hashes(output)
            self.assertEqual(sorted(after), sorted(before))
            changed = sorted(name for name in before if after[name] != before[name])
            self.assertFalse(
                changed, f"failed analysis partially replaced the prior packet: {changed}"
            )
            self.assertEqual(
                sorted(path.name for path in output.parent.iterdir()),
                ["packet"],
                "failed analysis left a staging directory behind",
            )

    def test_failure_does_not_publish_a_new_partial_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            real_write_text = Path.write_text

            def fail_call_graph(path, *args, **kwargs):
                if path.name == "call-graph.json":
                    raise OSError("injected packet write failure")
                return real_write_text(path, *args, **kwargs)

            with mock.patch.object(Path, "write_text", fail_call_graph):
                with self.assertRaisesRegex(OSError, "injected packet write failure"):
                    with contextlib.redirect_stdout(io.StringIO()):
                        analyze_program("mayhem", output)

            self.assertFalse(output.exists(), "failed analysis published a partial packet")
            self.assertEqual(list(output.parent.iterdir()), [])

    def test_missing_program_removes_staging(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program('does-not-exist-test-only', root / 'packet'), 1)
            self.assertEqual(list(root.iterdir()), [])

    def test_late_empty_output_directory_is_preserved(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / 'packet'
            build = analyzer._build_packet
            def late_writer(*args):
                result = build(*args)
                output.mkdir()
                return result
            with mock.patch.object(analyzer, '_build_packet', late_writer), contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, 'changed during analysis'):
                    analyze_program('mayhem', output)
            self.assertEqual(list(output.iterdir()), [])
            self.assertEqual(list(root.iterdir()), [output])

    def test_successful_replacement_retains_prior_packet_and_late_addition(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / 'packet'
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program('mayhem', output), 0)
            before = packet_hashes(output)
            output.chmod(0o700)
            build = analyzer._build_packet
            def late_writer(*args):
                result = build(*args)
                (output / 'late.txt').write_bytes(b'late user evidence')
                return result
            with mock.patch.object(analyzer, '_build_packet', late_writer), contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program('pump', output), 0)
            backups = list(root.glob('.packet.previous-*'))
            self.assertEqual(len(backups), 1)
            after = packet_hashes(backups[0])
            self.assertEqual({name: after[name] for name in before}, before)
            self.assertEqual((backups[0] / 'late.txt').read_bytes(), b'late user evidence')
            self.assertEqual(output.stat().st_mode & 0o777, 0o700)

    def test_native_publication_failure_preserves_late_output(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / 'packet'
            rename = publisher.rename_directory
            def late_writer(source, destination, **kwargs):
                output.mkdir()
                return rename(source, destination, **kwargs)
            with mock.patch.object(publisher, 'rename_directory', late_writer), contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaises(FileExistsError):
                    analyze_program('mayhem', output)
            self.assertEqual(list(output.iterdir()), [])
            self.assertEqual(list(root.iterdir()), [output])

    def test_exchange_race_retains_recovery_packet(self):
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            output = root / 'packet'
            with contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(analyze_program('mayhem', output), 0)
            rename = publisher.rename_directory
            calls = 0
            def late_writer(source, destination, **kwargs):
                nonlocal calls
                calls += 1
                if calls == 1:
                    output.rename(root / 'moved-old')
                    output.mkdir()
                    (output / 'other.txt').write_bytes(b'other writer')
                return rename(source, destination, **kwargs)
            with mock.patch.object(publisher, 'rename_directory', late_writer), contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, 'changed during publication'):
                    analyze_program('pump', output)
            self.assertEqual((output / 'other.txt').read_bytes(), b'other writer')
            retained = list(root.glob('.packet.staging-*'))
            self.assertEqual(len(retained), 1)
            self.assertTrue((retained[0] / 'manifest.json').is_file())
            self.assertTrue((root / 'moved-old' / 'manifest.json').is_file())


