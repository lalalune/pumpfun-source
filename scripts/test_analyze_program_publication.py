"""Evidence-packet publication checks for analyze_program."""

import contextlib
import io
from pathlib import Path
import tempfile
import unittest

from analyze_program import analyze_program


class AnalyzeProgramPublicationTests(unittest.TestCase):
    def test_unexpected_existing_entry_is_rejected_before_publication(self):
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "packet"
            output.mkdir()
            stale = output / "stale.txt"
            stale.write_text("not generated by this analysis\n")

            with contextlib.redirect_stdout(io.StringIO()):
                with self.assertRaisesRegex(ValueError, "unexpected packet entry"):
                    analyze_program("mayhem", output)

            self.assertEqual([path.name for path in output.iterdir()], ["stale.txt"])


if __name__ == "__main__":
    unittest.main()
